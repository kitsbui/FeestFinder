/** An exact price: 1.200.000₫ / 1,200,000₫. */
const exact = (n, vi) => Number(n || 0).toLocaleString(vi ? 'vi-VN' : 'en-US') + '₫';
/** A price in passing, the way the design writes tier notes: 900k · 2.4M. */
function short(n, vi) {
  const a = Number(n || 0);
  if (a >= 1e6) { const s = (a / 1e6).toFixed(1).replace(/\.0$/, ''); return (vi ? s.replace('.', ',') : s) + (vi ? 'tr' : 'M'); }
  return Math.round(a / 1000) + 'k';
}

/** One row of the dashboard events table, from /organizer/events. */
function toEvent(e) {
  return {
    id:e.id, slug:e.slug, title:e.title, mon:e.mon, day:e.day,
    art: e.coverUrl ? 'url("' + e.coverUrl + '") center/cover no-repeat' : e.art,
    live: e.status === 'live', status:e.statusLabel, meta:e.meta,
    views:{ en:cnum(e.views, false), vi:cnum(e.views, true) },
    saves:{ en:cnum(e.saves, false), vi:cnum(e.saves, true) },
    clicks:{ en:cnum(e.clicks, false), vi:cnum(e.clicks, true) },
    hasPerf:e.hasPerformance, perf:null
  };
}

/** /organizer/events/:id/performance → the shape the drawer reads. */
function toPerf(d, vi) {
  const f = d.funnel.map(x => x.value);
  return {
    cap:d.capacity, sold:d.sold, daysLeft:d.daysLeft, pace:d.pacePerDay, need:d.needPerDay,
    projection:d.projection, verdict:d.verdict,
    funnel:f,
    trend:d.trend.map(t => t.sold),
    from: d.trend.length ? d.trend[0].day : '', to: d.trend.length ? d.trend[d.trend.length - 1].day : '',
    sources:d.sources.map(s => [s.key, s.pct]),
    tiers:d.tiers.map(t => ({ n:t.name, sold:t.sold, cap:t.capacity })),
    prev: d.vsPrevious ? { label:d.vsPrevious.label, rows:d.vsPrevious.rows.map(r => [r.label, r.value, r.good]) } : null
  };
}

/** Fill the module arrays in place, so a sign-in needs no page reload. */
function applyOrg(d) {
  VENUES.length = 0;
  (d.venues || []).forEach(v => VENUES.push({ id:v.id, name:v.name, addr:(v.address || '') + (v.area ? ', ' + v.area : '') }));
  EVENTS.length = 0;
  (d.events || []).forEach(e => EVENTS.push(toEvent(e)));
  ATTENDEES.length = 0;
  ((d.attendees && d.attendees.items) || []).forEach(a => ATTENDEES.push(a));
  if (d.attendees) {
    AT.kpis = d.attendees.kpis; AT.filters = d.attendees.filters;
    AT.privacy = d.attendees.privacy; AT.cursor = d.attendees.nextCursor;
  }
}
