/** 'dd/mm' + 'hh:mm' typed in the announce form → an ISO instant in Ho Chi Minh City. */
function vnIso(date, time) {
  const d = /^(\d{1,2})\s*\/\s*(\d{1,2})$/.exec((date || '').trim());
  const t = /^(\d{1,2}):(\d{2})$/.exec((time || '').trim());
  if (!d || !t) return null;
  const year = FF.now().getFullYear();
  const pad = (n) => String(n).padStart(2, '0');
  return year + '-' + pad(+d[2]) + '-' + pad(+d[1]) + 'T' + pad(+t[1]) + ':' + t[2] + ':00+07:00';
}
