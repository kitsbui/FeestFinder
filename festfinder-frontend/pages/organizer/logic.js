/** Compact counts the way the design writes them: 31.4K / 31,4K. */
function cnum(n, vi) {
  if (n === null || n === undefined) return '—';
  const loc = vi ? 'vi-VN' : 'en-US';
  const dec = (x, d) => { const s = x.toFixed(d); return vi ? s.replace('.', ',') : s; };
  if (Math.abs(n) >= 1e6) return dec(n / 1e6, 1) + 'M';
  if (Math.abs(n) >= 1000) return dec(n / 1000, 1) + 'K';
  return Number(n).toLocaleString(loc);
}
/** Money the way the design writes it: 3.42bn₫ / 3,42 tỷ₫ / −137M₫ / −137tr₫. */
function money(n, vi, dp) {
  if (n === null || n === undefined) return '—';
  const neg = n < 0 ? '−' : '', a = Math.abs(n);
  const dec = (x, d) => { const s = x.toFixed(d); return vi ? s.replace('.', ',') : s; };
  if (a >= 1e9) return neg + dec(a / 1e9, dp === undefined ? 2 : dp) + (vi ? ' tỷ₫' : 'bn₫');
  if (a >= 1e6) return neg + dec(a / 1e6, dp === undefined ? 0 : dp) + (vi ? 'tr₫' : 'M₫');
  return neg + Math.round(a).toLocaleString(vi ? 'vi-VN' : 'en-US') + '₫';
}
